/**
 * Централизованные ценовые ориентиры.
 *
 * ПРАВИЛО: здесь может стоять ТОЛЬКО утверждённая владельцем цена.
 * Рыночные вилки из исследования (200–500 тыс. за discovery и т.п.) —
 * это ориентиры рынка, а НЕ прайс студии, и в публичный UI они не идут.
 *
 * Пока цена диагностики не утверждена, `DIAGNOSTICS_PRICE = null` —
 * страницы рендерят честный блок «как формируется стоимость» вместо числа.
 * Чтобы опубликовать цену, достаточно заполнить объект ниже: UI подхватит
 * его автоматически на /diagnostika, /services и в блоке метода.
 */

export interface PricePoint {
  /** Отображаемое значение, например «180 000 ₽». Без «от», если цена фиксированная. */
  value: string
  /** Уточнение под ценой — что именно входит в эту сумму. */
  note?: string
}

/** Диагностика процессов. null → цена ещё не утверждена, число не показываем. */
export const DIAGNOSTICS_PRICE: PricePoint | null = null

/** Пилот одного процесса. null → показываем только состав работ и срок. */
export const PILOT_PRICE: PricePoint | null = null

/** Программы по ИИ. null → цена по запросу. */
export const PROGRAM_PRICE: PricePoint | null = null

/** Есть ли хоть одна утверждённая цена — для условного рендера блоков. */
export const HAS_PUBLIC_PRICING =
  DIAGNOSTICS_PRICE !== null || PILOT_PRICE !== null || PROGRAM_PRICE !== null

/**
 * Факторы, от которых зависит стоимость. Показываются всегда — даже когда
 * самого числа нет. Это то, что закрывает вопрос «на какой порядок
 * рассчитывать» без выдуманного прайса.
 */
export const DIAGNOSTICS_FACTORS = [
  "Сколько процессов разбираем — один или несколько смежных",
  "Объём и состояние данных: выгрузки из систем или бумага и сканы",
  "Количество интервью и доступность владельцев процесса",
  "Нужен ли замер baseline на реальных операциях или хватает имеющегося учёта",
  "Требования к режиму работы с данными",
]

export const DIAGNOSTICS_NOT_INCLUDED = [
  "Разработка и внедрение — это следующий этап, отдельная смета",
  "Подготовка данных, OCR и оцифровка архивов",
  "Закупка оборудования и лицензий",
  "Аттестация информационных систем",
]
