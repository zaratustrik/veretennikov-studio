// Все вопросы плоским списком (включая vision) — для валидации, экспорта и % заполнения.
export const allQuestions: Question[] = [
  ...visionQuestions,
  ...stages.flatMap((s) => s.questions)
];

export function findQuestion(id: string): Question | undefined {
  return allQuestions.find((q) => q.id === id);
}

// Соответствие вопрос → этап (для экспорта/резюме).
export const questionStageMap: Record<string, { stageId: string; stageTitle: string }> = (() => {
  const map: Record<string, { stageId: string; stageTitle: string }> = {};
  for (const q of visionQuestions) {
    map[q.id] = { stageId: "vision", stageTitle: "Видение сайта" };
  }
  for (const s of stages) {
    for (const q of s.questions) {
      map[q.id] = { stageId: s.id, stageTitle: s.title };
    }
  }
  return map;
})();
