def apply(text: str) -> str:
    for a, b in FACT_FIXES:
        text = text.replace(a, b)
    for a, b in PHRASES:
        text = text.replace(a, b)
    return text

def walk(obj):
    if isinstance(obj, dict):
        return {k: walk(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [walk(x) for x in obj]
    if isinstance(obj, str):
        return apply(obj)
    return obj

